#!/usr/bin/env python3
"""Rebuild docs/lexicon.seed.json from lexicon/styles/*.json.

One source of truth: the style files. The seed is generated, so a style can be
edited, added, or deleted without anyone hand-merging a 90-row JSON blob.
Validation is not decorative -- a duplicate id or an empty style means the picker
silently favours whichever file happened to parse first.

    python3 tools/build_lexicon.py          # write the seed
    python3 tools/build_lexicon.py --check  # fail if the seed is stale
"""
import json
import pathlib
import sys

HERE = pathlib.Path(__file__).resolve().parent.parent
STYLES = HERE / "lexicon" / "styles"
SEED = HERE / "docs" / "lexicon.seed.json"


def build():
    entries = {"names": [], "moves": []}
    seen = set()
    problems = []
    files = sorted(STYLES.glob("*.json"))
    if not files:
        problems.append("no style files found")
    for f in files:
        try:
            d = json.loads(f.read_text())
        except Exception as e:
            problems.append(f"{f.name}: not valid JSON ({e})")
            continue
        sid = d.get("id") or f.stem
        if sid != f.stem:
            problems.append(f"{f.name}: id {sid!r} does not match filename")
        for kind, prefix in (("names", "n"), ("moves", "m")):
            rows = d.get(kind) or []
            if not rows:
                problems.append(f"{f.name}: no {kind}")
            for text in rows:
                text = " ".join(str(text).split())
                # within a style, not across: "clanker" belongs to several, and
                # collapsing it would quietly delete the word from most of them.
                key = (sid, kind, text.lower())
                if key in seen:
                    problems.append(f"{f.name}: duplicate {kind} entry {text!r}")
                    continue
                seen.add(key)
                entries[kind].append({
                    "id": f"{prefix}{len(entries[kind]) + 1:03d}",
                    "text": text,
                    "style": sid,
                    "used": 0,
                    "last": 0,
                })
    seed = {
        "version": 2,
        "note": "GENERATED by tools/build_lexicon.py from lexicon/styles/*.json. "
                "Edit the style files, not this.",
        "styles": sorted({e["style"] for e in entries["names"] + entries["moves"]}),
        "names": entries["names"],
        "moves": entries["moves"],
    }
    return seed, problems


def main():
    seed, problems = build()
    if problems:
        print("refusing to write: the style files have problems")
        for p in problems:
            print("  -", p)
        return 1
    body = json.dumps(seed, indent=1, ensure_ascii=False) + "\n"
    if "--check" in sys.argv:
        current = SEED.read_text() if SEED.exists() else ""
        if current != body:
            print("docs/lexicon.seed.json is STALE -- run: python3 tools/build_lexicon.py")
            return 1
        print(f"seed is current: {len(seed['names'])} names, {len(seed['moves'])} moves, "
              f"{len(seed['styles'])} styles")
        return 0
    SEED.parent.mkdir(parents=True, exist_ok=True)
    SEED.write_text(body)
    print(f"wrote {SEED.relative_to(HERE)}: {len(seed['names'])} names, "
          f"{len(seed['moves'])} moves, {len(seed['styles'])} styles "
          f"({', '.join(seed['styles'])})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
